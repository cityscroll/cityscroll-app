export function getSeqraSourceRegistryEntry(sourceId) {
  return SEQRA_SOURCE_REGISTRY.find((entry) => entry.source_id === sourceId) ?? null;
}

export function seqraSourceRegistryByTier() {
  const byTier = { 1: [], 2: [], 3: [], 4: [] };
  for (const entry of SEQRA_SOURCE_REGISTRY) byTier[entry.tier].push(entry.source_id);
  return byTier;
}
