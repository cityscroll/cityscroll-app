/**
 * SEQRA/CEQR source registry: every source this workstream is authorized to
 * inventory, with the tier priority from the commission and the fields the
 * source-receipt contract requires. Runtime fields (`observed_latency`,
 * `last_success_at`, `last_row_count`, `last_content_hash`) start `null` and
 * are overlaid by a `--refresh` run; they never carry a fabricated value.
 *
 * `access_type` distinguishes what this card measures from what it only
 * inventories:
 *   - "soda_api": Tier 1 structured source profiled live over Socrata SODA.
 *   - "existing_internal_corpus": already materialized inside CityScroll;
 *     the SEQRA/CEQR-specific subset is not yet query-scoped.
 *   - "discovery_probe": a single bounded, polite HTTP request records
 *     reachability only -- never parsed into a population count.
 *   - "discovery_only": registered from the commission text with no live
 *     request attempted in SEQRA-01; a later card owns the adapter.
 */

